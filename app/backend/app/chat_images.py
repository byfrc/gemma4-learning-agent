"""Validated image attachments for local multimodal chat."""
from __future__ import annotations

import base64
from io import BytesIO
from pathlib import Path
import warnings

from PIL import Image, ImageOps, UnidentifiedImageError

IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp"}
MAX_IMAGES = 4


def prepare_image(payload: bytes) -> tuple[str, str]:
    """Return a bounded model image and a small inline preview, both JPEG."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(BytesIO(payload)) as original:
                if original.format not in {"PNG", "JPEG", "WEBP"}:
                    raise ValueError("Use a PNG, JPEG, or WebP image.")
                if original.width * original.height > 40_000_000:
                    raise ValueError("Image exceeds the 40-megapixel limit.")
                image = ImageOps.exif_transpose(original)
                image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
                if image.mode in {"RGBA", "LA"} or "transparency" in image.info:
                    rgba = image.convert("RGBA")
                    image = Image.new("RGB", rgba.size, "white")
                    image.paste(rgba, mask=rgba.getchannel("A"))
                else:
                    image = image.convert("RGB")
                model = BytesIO()
                image.save(model, format="JPEG", quality=92)
                image.thumbnail((320, 240), Image.Resampling.LANCZOS)
                preview = BytesIO()
                image.save(preview, format="JPEG", quality=80)
        return (
            base64.b64encode(model.getvalue()).decode("ascii"),
            "data:image/jpeg;base64," + base64.b64encode(preview.getvalue()).decode("ascii"),
        )
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError, Image.DecompressionBombWarning) as exc:
        raise ValueError("This image cannot be read. Use a valid PNG, JPEG, or WebP file.") from exc


def image_path(db_path: Path, conversation_id: str, attachment_id: str) -> Path:
    # Both identifiers are generated by the server; validate them before use.
    from uuid import UUID
    return db_path.parent / "chat_images" / str(UUID(conversation_id)) / (UUID(attachment_id).hex + ".bin")


def add_history_images(history: list[dict], db_path: Path, conversation_id: str, current_images: list[str]) -> None:
    """Keep recent image context, with the current message taking priority."""
    remaining = MAX_IMAGES - len(current_images)
    for message in reversed(history[:-1]):
        images = []
        for attachment in message.get("attachments", []):
            if attachment.get("kind") != "image" or remaining <= 0:
                continue
            try:
                path = image_path(db_path, conversation_id, attachment["attachment_id"])
                model_image, _ = prepare_image(path.read_bytes())
            except (KeyError, OSError, ValueError):
                continue
            images.append(model_image)
            remaining -= 1
        if images:
            message["images"] = images
    if current_images:
        history[-1]["images"] = current_images
